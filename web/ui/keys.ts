/**
 * Есть ли у клавиши на этом элементе собственное поведение (открыть список,
 * вставить символ, переключиться в редактируемой области) — тогда глобальную
 * горячую клавишу нужно пропустить и отдать событие элементу.
 *
 * Общее место для всех потребителей: панель транспорта пропускает так
 * пробел (иначе он переключал бы воспроизведение поверх ввода в текстовом
 * поле фильтра или списка скорости), карточка узла — Escape (иначе он
 * закрывал бы карточку поверх отмены ввода в поле или закрытия открытого
 * списка). Раньше у транспорта была своя копия под именем `ownsSpaceKey` —
 * второй потребитель с тем же вопросом означал, что помощник общий, а не
 * принадлежит одному модулю.
 */
export function ownsTextInput(target: EventTarget | null): boolean {
  if (!(target instanceof HTMLElement)) return false;
  const tag = target.tagName;
  if (tag === 'INPUT' || tag === 'SELECT' || tag === 'TEXTAREA') return true;
  return target.isContentEditable;
}
