/**
 * Полосы холста, занятые интерфейсом. Значения — экранные пиксели, считаются
 * от соответствующего края окна и включают отступ панели от края: панель
 * отступает от края, и этот отступ — такая же занятая полоса, как и она сама.
 */
export interface ReservedStrips {
  /** Слева: панель фильтров. */
  left: number;
  /** Справа: карточка узла. */
  right: number;
  /** Снизу: строка состояния и панель транспорта. */
  bottom: number;
}

/**
 * Прямоугольник холста, свободный от панелей интерфейса: в него вписывается
 * дерево и в него же наводится камера по Enter в поиске.
 *
 * Все слои интерфейса лежат поверх холста и почти непрозрачны, поэтому
 * вписывание во всё окно прятало бы под ними края дерева — а достать их можно
 * было бы только ручным панорамированием, которое навсегда выключает
 * автовписывание.
 *
 * Слева, в отличие от низа и правого края, мало вычесть ширину: отсчёт идёт от
 * левого края, и облако, вписанное в суженный прямоугольник, всё равно
 * центрировалось бы поверх панели. Поэтому левая полоса возвращается ещё и
 * отдельно — как начало прямоугольника. Правую границу двигать не нужно:
 * вписывание центрирует облако в [left, left + width], и вычитания ширины
 * достаточно.
 *
 * Отдельный модуль, а не выражение внутри точки входа: сами полосы приходится
 * мерить по DOM, а вот арифметика над ними — чистая, и только так её можно
 * проверить тестом. Правая полоса до этого не была покрыта ничем, при том что
 * левая имеет собственный сквозной тест.
 *
 * Ширина и высота не опускаются ниже одного пикселя: панели могут не помещаться
 * в узкое окно, и нулевой или отрицательный прямоугольник дал бы вписыванию
 * деление на ноль вместо картинки.
 */
export function freeViewBox(
  canvasWidth: number,
  canvasHeight: number,
  strips: ReservedStrips,
): { left: number; width: number; height: number } {
  const left = Math.max(0, strips.left);
  const right = Math.max(0, strips.right);
  const bottom = Math.max(0, strips.bottom);
  return {
    left,
    width: Math.max(1, canvasWidth - left - right),
    height: Math.max(1, canvasHeight - bottom),
  };
}
