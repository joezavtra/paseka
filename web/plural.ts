/**
 * Правило русских числительных — одно на весь интерфейс. Раньше оно было
 * записано трижды: общий `plural` в точке входа, счётчик файлов в подписи узла
 * и согласование причастия в карточке узла, — и каждая копия сама помнила про
 * исключение на 11–14. Три копии одного правила означают, что «11 файла»
 * появится ровно в той из них, которую забудут поправить.
 */

/**
 * Какая из трёх форм нужна числу: 0 — как у «одного», 1 — как у «двух-четырёх»,
 * 2 — как у «пяти». Знак и дробная часть не влияют на выбор формы, поэтому
 * число приводится к модулю целого прямо здесь: иначе каждый вызывающий помнил
 * бы про это сам (и один из них рано или поздно забыл бы).
 */
export function pluralForm(n: number): 0 | 1 | 2 {
  const abs = Math.abs(Math.trunc(n));
  const tens = abs % 100;
  const ones = abs % 10;
  if (tens >= 11 && tens <= 14) return 2;
  if (ones === 1) return 0;
  if (ones >= 2 && ones <= 4) return 1;
  return 2;
}

/** Счётная подпись «число + слово»: 1 коммит, 2 коммита, 5 коммитов. */
export function plural(n: number, one: string, few: string, many: string): string {
  return `${n} ${[one, few, many][pluralForm(n)]}`;
}
