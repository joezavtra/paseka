/**
 * Кто на самом деле разместил путь на экране — воркер, а не главный поток,
 * который его об этом только спрашивает.
 *
 * Ответ воркера о позициях (`LayoutPositions`) относится к конкретной эпохе
 * (см. `web/layout/protocol.ts`): между отправкой очередного `update` и
 * приходом ответа на него воркер продолжает присылать позиции по СТАРОЙ
 * эпохе — обычные тики симуляции, которые ничего не знают о пути, родившемся
 * в главном потоке уже после отправки. Если считать «путь получил позицию»
 * по текущей маске главного потока, а не по маске, отправленной вместе с той
 * эпохой, которую воркер сейчас эхует, — только что родившийся путь
 * пометится размещённым по данным, в которых его попросту нет:
 * `NodeStore.positions()` заполняет только активные по СВОЕЙ маске, и на
 * этой позиции окажется тихий нуль, неотличимый от настоящей мировой
 * координаты.
 *
 * Этот модуль не знает ни про `self`, ни про Worker, ни про DOM — только про
 * числа и типизированные массивы, поэтому проверяется тестами напрямую, как
 * `NodeStore` рядом.
 */

/** Держит маски, отправленные вместе с ещё не устаревшими эпохами. */
export interface PlacementTracker {
  readonly pending: Map<number, Uint8Array>;
}

/**
 * Сколько масок держим одновременно. Живой карте хватает одной-двух записей:
 * каждый `update` завершается ответом воркера, а тот вычищает всё строго
 * младше своей эпохи. Предел нужен на случай, когда ответа нет вовсе
 * (воркер умер, стоит на брейкпоинте) — иначе карта росла бы на
 * `Uint8Array(pathCount)` за каждый `applyDelta`. Восемь — заведомо больше
 * нормы и всё ещё пренебрежимо по памяти.
 */
export const MAX_PENDING_EPOCHS = 8;

export function createPlacementTracker(): PlacementTracker {
  return { pending: new Map() };
}

/**
 * Запоминает маску, отправленную вместе с этой эпохой. Зовётся при каждой
 * отправке `update`, до postMessage — `active` не копируется: postMessage
 * без списка передачи клонирует буфер, а не отбирает его, так что этот же
 * объект остаётся годным на стороне главного потока.
 */
export function recordEpoch(tracker: PlacementTracker, epoch: number, active: Uint8Array): void {
  tracker.pending.set(epoch, active);

  // Свежие эпохи важнее старых: ответ на давно отправленную уже не придёт, а
  // если и придёт — молча отбросится как неизвестная. Эпохи нумеруются строго
  // по возрастанию и не повторяются, поэтому порядок вставки в `Map` совпадает
  // с порядком эпох: лишнее снимаем с головы.
  while (tracker.pending.size > MAX_PENDING_EPOCHS) {
    const oldest = tracker.pending.keys().next();
    if (oldest.done) break;
    tracker.pending.delete(oldest.value);
  }
}

/**
 * Принимает ответ воркера: переносит позиции и поднимает `placed` только для
 * путей, которые были рисуемыми на момент эпохи, которую воркер сейчас
 * эхует, — не для текущей маски главного потока, которая уже может быть
 * новее. Путь, не попавший в маску этой эпохи (ещё не родился на момент её
 * отправки), не трогается вовсе: ни его позиция, ни его `placed` — иначе
 * устаревший ответ затёр бы, например, позицию, унаследованную от родителя
 * при рождении уже после этой эпохи, тихим нулём, не сбросив при этом
 * `placed` обратно.
 *
 * Молча ничего не делает, если эпоха неизвестна (протокольная аномалия —
 * например, ответ до первого `update`), а не роняет кадр.
 */
export function applyPositions(
  tracker: PlacementTracker,
  epoch: number,
  incoming: Float32Array,
  positions: Float32Array,
  placed: Uint8Array,
): void {
  const mask = tracker.pending.get(epoch);
  if (!mask) return;

  for (let path = 0; path < mask.length; path++) {
    if (mask[path] !== 1) continue;
    positions[path * 2] = incoming[path * 2]!;
    positions[path * 2 + 1] = incoming[path * 2 + 1]!;
    placed[path] = 1;
  }

  // Эпохи воркер эхует по возрастанию — откатиться в его потоке сообщений
  // нельзя, поэтому всё строго младше этой эпохи больше не понадобится.
  // Саму эпоху не трогаем: следующий тик может прийти с тем же номером,
  // прежде чем главный поток отправит новый `update`.
  for (const key of tracker.pending.keys()) {
    if (key < epoch) tracker.pending.delete(key);
  }
}
