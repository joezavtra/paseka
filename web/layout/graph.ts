import { DEFAULT_LAYOUT_PARAMS, type LayoutParams } from './params.js';

export interface ActiveLinks {
  /** Идентификаторы путей-родителей. */
  source: Uint32Array;
  /** Идентификаторы путей-потомков. */
  target: Uint32Array;
}

const DIR_RADIUS = 3;
const MIN_RADIUS = 2.5;
const MAX_RADIUS = 40;

/**
 * Насколько корень из числа коммитов прибавляет к радиусу.
 *
 * Множитель заметно больше прежнего «построчного» неспроста: коммитов у файла
 * единицы и десятки там, где строк были сотни и тысячи. Замерено на этом же
 * репозитории: медиана — 3 коммита на файл, максимум — 23. На прежнем
 * множителе 0.6 такой разброс дал бы радиусы от 3.5 до 5.4 пикселя, то есть
 * дерево из одинаковых точек, а смена метрики прошла бы впустую. При 2.6
 * те же данные дают от 5.1 до 15 — разница видна, и самые правленые файлы
 * заодно перешагивают порог собственной подписи.
 */
const COMMIT_WEIGHT = 2.6;

/**
 * Радиус узла растёт как корень из числа коммитов, задевших файл, — так видно,
 * где кипит работа, а не где просто много строк: сгенерированный файл на
 * десять тысяч строк, тронутый однажды, больше не спорит размером с ядром
 * проекта, которое правят каждую неделю. Корень нужен, чтобы разница между
 * редким и частым файлом была заметна, но не рвала масштаб.
 *
 * У обычной директории вес всегда 0 (см. `visibility.weight`), поэтому её
 * радиус остаётся `DIR_RADIUS`; у свёрнутой вес — сумма живых потомков, и тем
 * же законом, но от директорийной базы, она обязана расти вместе с ним: иначе
 * сворачивание рисовало бы любую папку точкой в три пикселя независимо от
 * того, сколько в ней спрятано работы.
 */
export function radiusFor(commits: number, isDir: boolean): number {
  const base = isDir ? DIR_RADIUS : MIN_RADIUS;
  return Math.min(MAX_RADIUS, base + Math.sqrt(Math.max(0, commits)) * COMMIT_WEIGHT);
}

/**
 * Сила отталкивания узла: у листа слабая, у ветвящегося каталога — от радиуса.
 * «Лист» здесь — узел без рисуемых потомков, то есть файл, свёрнутая папка или
 * папка, чьё содержимое скрыто: на экране все трое ведут себя одинаково.
 *
 * Заряд в d3-force действует между всеми парами и растёт как квадрат числа
 * узлов: кластер из сотни файлов расталкивает соседние кластеры с силой,
 * которой нечего противопоставить, кроме цепочки рёбер, — и она растягивается
 * в ниточку через полэкрана. Замерено на дереве из шести кластеров по 120
 * файлов на концах семизвенных цепочек транзитных папок: при полном заряде у
 * всех узлов среднее звено цепочки — 389 при длине покоя 24 и облако радиусом
 * 3307; со слабым зарядом листьев и радиусом действия 200 — 69 и 801.
 *
 * Умолчания и границы живут в web/layout/params.ts: их можно крутить панелью
 * настроек, не пересобирая приложение.
 */
export function chargeStrengthFor(
  radius: number,
  children: number,
  params: LayoutParams = DEFAULT_LAYOUT_PARAMS,
): number {
  if (children === 0) return params.leafCharge;
  return params.dirCharge + Math.max(0, radius) * params.dirChargePerRadius;
}

/**
 * Длина ребра «папка → потомок» по следам обоих концов.
 *
 * Раньше длина считалась от числа прямых детей и упиралась в потолок. Это и
 * было причиной того, что структура папок не читалась: у папки с двумя
 * тысячами файлов кружки физически укладываются в диск радиусом около
 * четырёхсот пикселей, а пружины тянули их к родителю на шестьдесят. Папка
 * жила под постоянным натяжением, содержимое было сжато внутрь, а соседние
 * папки висели на таких же коротких рёбрах от общего предка и перекрывались.
 * Замерено на синтетическом монорепозитории (8263 рисуемых узла): медианное
 * ребро было растянуто в 3.3 раза против длины покоя, на хвосте — в 6.2, и
 * половина узлов сидела за пределами следа своей папки. После перехода на
 * следы растяжение упало до 1.2 и 2.4 — пружины перестали воевать с
 * разведением кружков.
 *
 * Одного этого мало, и замер это показал прямо: примесь чужих узлов в диске
 * папки выросла с 7.3% до 9.8%, а узлов вне следа своей папки стало 61.6%
 * вместо 49.5%. Пружины делали двойную работу — сжимали папку и удерживали её
 * содержимое рядом; сняв сжатие, теряем и удержание. Возвращают его групповые
 * силы (см. web/layout/groups.ts).
 *
 * Теперь длина выводится из разности следов: центр ребёнка равномерно лежит
 * внутри диска радиуса `R(родителя) − R(ребёнка)`, а `folderFill` говорит,
 * какую долю этого разрешённого радиуса брать за длину покоя.
 *
 * Разность, а не доля радиуса родителя, — потому что так формула сама
 * вырождается в нужное поведение по краям. У транзитной папки с единственным
 * ребёнком следы совпадают, разность равна нулю, срабатывает нижний зажим — и
 * цепочки каталогов остаются короткими без единой отдельной ветки. У папки с
 * одним огромным поддеревом и горстью файлов рядом большое поддерево садится
 * на родителя (оно и есть содержимое папки), а файлы уходят на периферию;
 * единой длиной на всех детей так не получится.
 */
export function linkDistanceFor(
  parentFootprint: number,
  childFootprint: number,
  params: LayoutParams = DEFAULT_LAYOUT_PARAMS,
): number {
  const room = Math.max(0, parentFootprint - childFootprint) * params.folderFill;
  return Math.min(params.linkMax, Math.max(params.linkMin, room));
}

/**
 * Жёсткость ребра «папка → потомок».
 *
 * У транзитной папки ребро жёсткое: разводить нечего, а мягкое звено — это
 * ровно та пружина, которая растягивает цепочку. У ветвящейся папки ребро
 * мягче: детям надо дать разойтись по кольцу, и слишком жёсткая привязка
 * сминала бы их в кучу вокруг родителя.
 */
export function linkStrengthFor(
  children: number,
  params: LayoutParams = DEFAULT_LAYOUT_PARAMS,
): number {
  return children <= 1 ? params.chainStrength : params.branchStrength;
}

/**
 * Сколько детей у каждого пути среди присланных рёбер. Индекс — идентификатор
 * пути, значение — число рисуемых потомков.
 *
 * Считается по рёбрам, а не по дереву целиком: рёбра уже отфильтрованы
 * рисуемой маской (скрытое поддерево в них не входит, свёрнутая папка детей не
 * имеет), а значит и ветвление получается то, которое видно на экране, а не то,
 * что записано в истории.
 */
export function countChildren(linkSource: Uint32Array, pathCount: number): Uint32Array {
  const children = new Uint32Array(pathCount);
  for (let i = 0; i < linkSource.length; i++) children[linkSource[i]!]++;
  return children;
}

/**
 * Рёбра дерева между узлами присланной маски, в идентификаторах путей. Маска
 * обычно рисуемая, а не живая: main.ts кормит сюда `scene.active`, где живой,
 * но скрытый или свёрнутый путь уже вычеркнут.
 * Плотной перенумерации больше нет: она ломала бы позиции при каждом
 * изменении состава маски, а состав меняется на каждом коммите.
 */
export function buildActiveLinks(active: Uint8Array, parent: Uint32Array): ActiveLinks {
  const source: number[] = [];
  const target: number[] = [];
  for (let path = 0; path < active.length; path++) {
    if (active[path] === 0) continue;
    const parentId = parent[path];
    if (parentId === path) continue; // корень
    if (active[parentId] === 0) continue;
    source.push(parentId);
    target.push(path);
  }
  return { source: Uint32Array.from(source), target: Uint32Array.from(target) };
}

/**
 * Пути, ставшие рисуемыми со времени прошлого применения. Разница движка
 * времени отвечает на вопрос «что родилось в истории», а этот список — на
 * другой: «что появилось на сцене». С видимостью это уже не одно и то же —
 * развёрнутая папка выпускает наружу узлы, которые в истории не менялись.
 *
 * Чистая функция: ни `prevDrawn`, ни `drawn` не мутирует, поэтому вызывающий
 * сам решает, когда переносить `drawn` в `prevDrawn` для следующего вызова.
 */
export function diffBorn(prevDrawn: Uint8Array, drawn: Uint8Array): Uint32Array {
  const born: number[] = [];
  for (let path = 0; path < drawn.length; path++) {
    if (drawn[path] === 1 && prevDrawn[path] === 0) born.push(path);
  }
  return Uint32Array.from(born);
}
