/** Главный поток → воркер: однократная настройка размера мира и структуры дерева. */
export interface LayoutInit {
  type: 'init';
  /** Длина всех массивов по узлам; индекс — идентификатор пути. */
  pathCount: number;
  /**
   * Родитель каждого пути; индекс — идентификатор пути. Не меняется за сессию,
   * поэтому шлётся один раз: воркер сам поднимается от любого узла к любому
   * предку без подсказки «кто чей родитель» в каждом обновлении.
   */
  parent: Uint32Array;
  /** Фиксированный seed: два запуска на одном репозитории дают похожую картинку. */
  seed: number;
}

/**
 * Главный поток → воркер: изменение состава и геометрии.
 *
 * Живость передаётся маской, а не списками added/removed: маска — авторитетный
 * источник (её строит движок времени), и воркер её просто копирует к себе, не
 * выводя ничего из списков. `added` остаётся, но только как ответ на вопрос
 * «кого рождать» — список путей, которых не было в предыдущей маске. Само по
 * себе появление в этом списке ничего не говорит о живости: её сообщает `active`.
 */
export interface LayoutUpdate {
  type: 'update';
  /** Рисуемая маска; индекс — идентификатор пути. Живой, но скрытый или свёрнутый путь сюда не входит. */
  active: Uint8Array;
  /** Идентификаторы путей, вошедших в симуляцию — кандидаты на рождение. */
  added: Uint32Array;
  /** Пути, у которых изменился радиус, и сами радиусы — параллельные массивы. */
  radiusIds: Uint32Array;
  radiusValues: Float32Array;
  /** Активные рёбра в идентификаторах путей. */
  linkSource: Uint32Array;
  linkTarget: Uint32Array;
}

/** Воркер → главный поток: пары x, y длиной pathCount * 2, индекс — путь. */
export interface LayoutPositions {
  type: 'positions';
  positions: Float32Array;
  /** «Температура» симуляции; ниже 0.02 картинка практически замерла. */
  alpha: number;
}

export type ToWorker = LayoutInit | LayoutUpdate;
export type FromWorker = LayoutPositions;
