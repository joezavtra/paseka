import { plural, pluralForm } from '../plural.js';

/** Начиная с какого экранного радиуса файл подписывается сам по себе. */
export const MIN_LABEL_RADIUS_PX = 9;
/** Сколько подписей файлов рисуется в кадре: дальше они превращаются в кашу. */
export const DEFAULT_LABEL_LIMIT = 24;
/**
 * Сколько подписей папок рисуется в кадре.
 *
 * Папка подписывается всегда, а не по размеру: имена каталогов — это карта
 * дерева, по ней читается, куда смотришь, и терять её на общем плане нельзя.
 * Предел здесь не правило отбора, а страховка от монорепозитория с тысячами
 * каталогов: он свой, отдельный от файлового, иначе папки съедали бы лимит
 * подписей у крупных файлов или наоборот.
 */
export const DEFAULT_FOLDER_LABEL_LIMIT = 160;
/**
 * Во сколько раз подпись обычной папки бледнее подписи файла.
 *
 * Папок на экране всегда много, и в полную силу их имена спорили бы с именами
 * файлов и с лучами авторов. Бледная подпись читается, когда её ищут глазами,
 * и не мешает, когда смотрят на другое. Крупная папка эту скидку не получает:
 * она и раньше подписывалась наравне с файлами, и её подпись — тот же ориентир.
 */
export const FOLDER_LABEL_ALPHA = 0.45;
/**
 * Ниже какой силы свечения имя изменённого файла уже не показывается.
 *
 * Имя вспыхивает вместе с самим файлом и гаснет вместе с ним: подпись живёт
 * ровно столько, сколько длится касание (см. RecentEvents), а не остаётся на
 * экране после того, как автор перешёл к следующему файлу.
 */
export const MIN_FLASH_LABEL = 0.05;
/**
 * До скольких совпадений поиск даёт мелкому узлу право на подпись.
 *
 * Обводка сама по себе полностью отвечает на вопрос «где нашлось»; подпись
 * добавляет к ней имя, и это помогает, пока подписей единицы. На удачном
 * образце совпадений бывают десятки, и почти всегда они лежат одним кластером:
 * весь лимит подписей уходит найденным, они ложатся друг на друга в пятне
 * размером с ноготь и не читаются, а подписи крупных узлов — единственный
 * ориентир на общем плане — исчезают. Получалось, что чем удачнее поиск, тем
 * хуже видно результат. Порог отсекает ровно этот случай: совпадений много —
 * работает одна обводка, а имя конкретного узла показывает наведение.
 */
export const MAX_LABELED_HITS = 8;
/** Поле в экранных пикселях за краем вида, в котором узел ещё считается видимым. */
const EDGE_MARGIN_PX = 40;
/** Ниже этой яркости узел считается погашенным фильтром и не подписывается сам собой. */
const DIMMED_ALPHA_THRESHOLD = 0.5;

/**
 * Русское числительное для счётчика файлов. Вынесено отдельной функцией и
 * покрыто трудными числами (11–14, 21, 111) намеренно: «11 файла» в подписи
 * читается как небрежность во всём инструменте. Само правило выбора формы —
 * общее для всего интерфейса (см. web/plural.ts), здесь только слово.
 */
export function pluralFiles(count: number): string {
  return plural(Math.abs(Math.trunc(count)), 'файл', 'файла', 'файлов');
}

/** Подпись узла: у свёрнутой папки — с числом спрятанных файлов. */
export function labelFor(name: string, files: number): string {
  return files > 0 ? `${name} · ${pluralFiles(files)}` : name;
}

/**
 * Клауза расхождения между карточкой узла и подписью на сцене: свёрнутая
 * папка может прятать скрытое поддерево, и тогда «файлов» в карточке (живых
 * в истории) больше, чем реально представлено одним кружком на сцене.
 * Молчать об этом нельзя — иначе пользователь видит два разных числа рядом
 * на экране без объяснения. Числительное без повторения слова «файл»: оно
 * уже названо в первой части фразы карточки, см. `web/ui/inspector.ts`.
 * Согласование причастия — то же правило выбора формы, что и у `pluralFiles`,
 * взятое из общего `pluralForm`: причастие стоит перед числом, поэтому готовая
 * строка `plural` здесь не годится, а вот выбор формы обязан быть тем же.
 */
export function representedClause(represented: number): string {
  const abs = Math.abs(Math.trunc(represented));
  const participle = pluralForm(abs) === 0 ? 'показан' : 'показано';
  return `на сцене ${participle} ${abs}`;
}

/** Всё, что нужно знать о сцене, чтобы решить, какие узлы подписывать. */
export interface LabelInput {
  /** Рисуемая маска; индекс — идентификатор пути. */
  active: Uint8Array;
  /** Пары x, y в мировых координатах. */
  positions: Float32Array;
  radius: Float32Array;
  /** Яркость узла от фильтра: 1 — попал, около нуля — погашен. */
  alpha: Float32Array;
  /** Найденное поиском; индекс — идентификатор пути. */
  hit: Uint8Array;
  /** Каталог ли путь; индекс — идентификатор пути. Каталоги подписываются всегда. */
  isDir: Uint8Array;
  /** Свечение узла от недавнего касания: 0 — нет, 1 — только что задет. */
  flash: Float32Array;
  /**
   * Сколько единиц в `hit` — считает проекция попаданий (web/state/search.ts),
   * та же, что заполняет саму маску. Здесь это не оптимизация, а вход правила:
   * право найденного на подпись зависит от того, сколько всего нашлось (см.
   * MAX_LABELED_HITS), а по маске это пришлось бы выяснять отдельным проходом.
   */
  hitCount: number;
}

/** Камера принимается структурно, чтобы тест не поднимал DOM. */
export interface LabelCamera {
  scale: number;
  toScreen(worldX: number, worldY: number): [number, number];
}

export interface LabelOptions {
  /** Путь под курсором мыши; -1 или отсутствие — наведения нет. */
  hovered?: number;
  /** Сколько подписей файлов разрешено вернуть. */
  limit?: number;
  /** Сколько подписей папок разрешено вернуть. */
  folderLimit?: number;
}

/** Отобранная подпись: чей это путь и с какой яркостью её рисовать. */
export interface LabelPick {
  path: number;
  /**
   * Множитель яркости подписи: 1 — в полную силу, меньше — бледнее. Умножается
   * на яркость самого узла при отрисовке, поэтому фильтр по-прежнему гасит
   * подпись вместе с узлом, а этот множитель отвечает только за то, насколько
   * подпись важна сама по себе.
   */
  alpha: number;
}

/**
 * Отбирает узлы для подписи на текущем кадре и возвращает их по убыванию
 * важности: наведённый — первым, за ним найденные поиском, потом только что
 * изменённые файлы, потом крупные узлы, и последними — папки. У каждой подписи
 * свой множитель яркости.
 *
 * Это порядок важности, а не порядок отрисовки: важное рисуется последним,
 * чтобы лечь поверх остального (см. слой подписей в web/render/scene.ts). Сам
 * порядок нужен ещё и обрезке по пределам — при нехватке места отсекается
 * хвост, то есть наименее важное.
 *
 * Правило отбора одного узла:
 * - рисуется (`active === 1`) — иначе подписывать нечего;
 * - погашенный фильтром (alpha < DIMMED_ALPHA_THRESHOLD) не подписывается,
 *   кроме наведённого: на него пользователь показывает явно, и молчать в
 *   ответ нельзя. Ни находка поиском, ни свежее изменение этой поблажки не
 *   дают — фильтр гасит узел осознанно, и подпись поверх погашенной ветки
 *   читалась бы как отмена фильтра;
 * - **папка подписывается всегда**, какого бы размера она ни была: имена
 *   каталогов — карта дерева, и на общем плане, где не видно ни одного
 *   крупного узла, только они и отвечают на вопрос «куда я смотрю». Бледнее
 *   файловых (FOLDER_LABEL_ALPHA), кроме крупных — те и раньше подписывались
 *   наравне;
 * - **изменённый файл подписывается, пока горит его вспышка**: имя появляется
 *   вместе со свечением от касания и гаснет вместе с ним, так что во время
 *   воспроизведения видно, что именно правит автор, а не только куда бьёт луч;
 * - файл без свечения подписывается, если он крупный (экранный радиус ≥
 *   MIN_LABEL_RADIUS_PX), наведён или найден поиском, причём находка даёт это
 *   право лишь пока совпадений не больше MAX_LABELED_HITS (см. там же, почему
 *   удачный поиск иначе выдавливает с экрана все прочие подписи);
 * - виден на экране (с полем в EDGE_MARGIN_PX по обе стороны).
 *
 * Пределы у папок и файлов раздельные: общий предел означал бы, что дерево из
 * сотни каталогов оставляет крупные файлы без подписей — или наоборот.
 *
 * Порядок проверок в коде намеренно ставит правило отбора перед проверкой
 * видимости: и размер, и вспышка, и признак каталога — дешёвые обращения к
 * массивам, а видимость требует `camera.toScreen()`, который на каждый вызов
 * аллоцирует пару координат.
 *
 * `LabelInput` намеренно не принимает маску `placed` (см. web/main.ts) — это
 * осознанный выбор, а не недосмотр. Узел без настоящей позиции от раскладки
 * рисуется у позиции родителя (см. `applyDelta` в web/main.ts): это уже
 * честная экранная точка, а не заглушка мирового нуля, так что отдельная
 * проверка `placed` здесь дублировала бы задачу, которую `applyDelta` уже
 * решил на уровне позиций.
 */
export function selectLabels(
  input: LabelInput,
  camera: LabelCamera,
  width: number,
  height: number,
  options: LabelOptions = {},
): LabelPick[] {
  const hovered = options.hovered ?? -1;
  const limit = options.limit ?? DEFAULT_LABEL_LIMIT;
  const folderLimit = options.folderLimit ?? DEFAULT_FOLDER_LABEL_LIMIT;
  // Много совпадений — находка перестаёт быть поводом для подписи вовсе: ни
  // права мелкому узлу, ни места в начале очереди. Оба следствия обязаны
  // сниматься вместе, иначе крупные найденные всё равно вытеснили бы прочие
  // подписи из лимита, просто без каши из мелких.
  const hitsMayLabel = input.hitCount > 0 && input.hitCount <= MAX_LABELED_HITS;

  const picked: number[] = [];
  const screenRadius: number[] = [];
  const priority: number[] = [];
  const brightness: number[] = [];

  for (let path = 0; path < input.active.length; path++) {
    if (input.active[path] !== 1) continue;

    const isHovered = path === hovered;
    const dimmed = input.alpha[path]! < DIMMED_ALPHA_THRESHOLD;
    // Погашенный узел молчит, кроме наведённого — на него пользователь
    // показывает явно, и ответ на явный жест не может быть тишиной.
    if (dimmed && !isHovered) continue;

    // Экранный радиус не требует toScreen() — только масштаб. Всё правило
    // отбора решается здесь, до перевода в экранные координаты: оно же и
    // ранний выход для общего плана.
    const r = Math.max(0, input.radius[path]!) * camera.scale;
    const isDir = input.isDir[path] === 1;
    const isHit = hitsMayLabel && input.hit[path] === 1;
    const large = r >= MIN_LABEL_RADIUS_PX;
    const flash = Math.min(1, Math.max(0, input.flash[path]!));
    // Свечение бывает и у папки — свёрнутая вспыхивает за всё, что внутри, —
    // но временная подпись адресована файлам: у папки имя и так на экране.
    const flashing = !isDir && flash > MIN_FLASH_LABEL;
    if (!isHovered && !isDir && !large && !isHit && !flashing) continue;

    const [sx, sy] = camera.toScreen(input.positions[path * 2]!, input.positions[path * 2 + 1]!);
    if (sx + r < -EDGE_MARGIN_PX || sy + r < -EDGE_MARGIN_PX) continue;
    if (sx - r > width + EDGE_MARGIN_PX || sy - r > height + EDGE_MARGIN_PX) continue;

    picked.push(path);
    screenRadius.push(r);
    // Порядок важности: явный жест пользователя, его же поиск, свежее
    // изменение, крупный узел, карта каталогов.
    priority.push(isHovered ? 0 : isHit ? 1 : flashing ? 2 : isDir && !large ? 4 : 3);
    // Яркость: временная подпись гаснет вместе со вспышкой, обычная папка
    // бледнее файла, всё остальное — в полную силу.
    brightness.push(isHovered ? 1 : flashing ? flash : isDir && !large ? FOLDER_LABEL_ALPHA : 1);
  }

  // Сортируем индексы в parallel-массивах, а не сами пути: поиск радиуса по
  // пути через indexOf() на каждое сравнение был бы квадратичным.
  const order = picked.map((_, i) => i);
  order.sort((ai, bi) => {
    const diff = priority[ai]! - priority[bi]!;
    if (diff !== 0) return diff;
    // Внутри одной группы приоритета — по убыванию экранного радиуса.
    return screenRadius[bi]! - screenRadius[ai]!;
  });

  // Пределы считаются раздельно: подписи папок и файлов не отнимают места
  // друг у друга, поэтому карта каталогов не исчезает от того, что в кадр
  // попало много крупных файлов, и наоборот.
  const result: LabelPick[] = [];
  let files = 0;
  let folders = 0;
  for (const i of order) {
    const path = picked[i]!;
    const isFolderLabel = priority[i] === 4;
    if (isFolderLabel) {
      if (folders >= folderLimit) continue;
      folders++;
    } else {
      if (files >= limit) continue;
      files++;
    }
    result.push({ path, alpha: brightness[i]! });
  }
  return result;
}
